# acentos: 2 linhas acima da letra; cedilha: 1 linha abaixo
_ACENTO = {"´": "...#. ..#..", "`": ".#... ..#..", "^": "..#.. .#.#.", "~": ".##.# #.##.", "¨": "..... .#.#."}
_COMPOSTA = {"Á": ("A", "´"), "À": ("A", "`"), "Â": ("A", "^"), "Ã": ("A", "~"), "É": ("E", "´"), "Ê": ("E", "^"),
             "Í": ("I", "´"), "Ó": ("O", "´"), "Ô": ("O", "^"), "Õ": ("O", "~"), "Ú": ("U", "´"), "Ü": ("U", "¨")}


def _glifo(ch: str) -> list[str]:
    """Linhas (10) do caractere: 2 de acento, 7 da letra, 1 abaixo."""
    ch = ch.upper()
    vazio = "....."
    if ch == "Ç":
        return [vazio, vazio, *_G["C"].split(), "..##."]
    if ch in _COMPOSTA:
        base, ac = _COMPOSTA[ch]
        return [*_ACENTO[ac].split(), *_G[base].split(), vazio]
    return [vazio, vazio, *(_G.get(ch) or _G["?"]).split(), vazio]


def largura(texto: str, px: float) -> float:
    return max(0, len(texto) * 6 - 1) * px


def svg(texto: str, px: float, sombra: str = "#06121c") -> str:
    """O texto em pixels de px x px. A sombra escura fica 1 pixel abaixo e à direita."""
    texto = texto.upper()
    rects = []
    for k, ch in enumerate(texto):
        for y, linha in enumerate(_glifo(ch)):
            x = 0
            while x < 5:
                if linha[x] == "#":
                    ini = x
                    while x < 5 and linha[x] == "#":
                        x += 1
                    rects.append((k * 6 + ini, y, x - ini))
                else:
                    x += 1
    w, h = largura(texto, px) + px, 10 * px + px
    corpo = "".join(f'<rect x="{(x + 1) * px:g}" y="{(y + 1) * px:g}" width="{n * px:g}" height="{px:g}"/>' for x, y, n in rects)
    letra = "".join(f'<rect x="{x * px:g}" y="{y * px:g}" width="{n * px:g}" height="{px:g}"/>' for x, y, n in rects)
    return (f'<svg class="px" width="{w:g}" height="{h:g}" viewBox="0 0 {w:g} {h:g}" shape-rendering="crispEdges" '
            f'aria-label="{html.escape(texto)}"><g fill="{sombra}">{corpo}</g><g fill="currentColor">{letra}</g></svg>')
